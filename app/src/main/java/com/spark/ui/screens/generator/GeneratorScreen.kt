    val aiClient: com.spark.data.network.SparkAIClient = org.koin.compose.koinInject()
    val context = LocalContext.current
    val scrollState = rememberScrollState()
    val coroutineScope = rememberCoroutineScope()
    val accountSession = remember { com.spark.data.local.AccountSessionManager.generation }

    // Persistent seen questions storage so questions NEVER repeat across app sessions
    var seenQuestionsSet by remember { mutableStateOf(SparkAISeenStorage.getSeen(context)) }

    // Multidisciplinary in-app questions feed initialized with unseen questions
    var suggestedQuestions by remember {
        mutableStateOf<List<QuestionCardItem>>(LocalSparkContent.getDiverseMultidisciplinaryMix(seenQuestionsSet))
    }
    var questionsAreAI by remember { mutableStateOf(false) }
    var generationFailed by remember { mutableStateOf(false) }
    var isRefreshingQuestions by remember { mutableStateOf(false) }

    // Active in-screen quest state
    var activeQuest by remember { mutableStateOf<SparkTaskDto?>(null) }
    var isGeneratingQuest by remember { mutableStateOf(false) }
    var selectedQuestionText by remember { mutableStateOf<String?>(null) }
    var questClaimed by remember { mutableStateOf(false) }

    // In-screen Wormhole Q&A chat state
    var wormholeQuestion by remember { mutableStateOf("") }
    var wormholeMessages by remember { mutableStateOf<List<ChatMessage>>(emptyList()) }
    var isWormholeThinking by remember { mutableStateOf(false) }

    // Refresh handler: requests brand-new non-repeating questions generated by AI and persists them
    fun refreshQuestionsList() {
        if (isRefreshingQuestions) return
        isRefreshingQuestions = true

        val currentQuestions = suggestedQuestions.map { it.question }.toSet()
        val updatedSeen = seenQuestionsSet + currentQuestions
        seenQuestionsSet = updatedSeen
        SparkAISeenStorage.addSeen(context, currentQuestions)

        coroutineScope.launch {
            try {
                val result = aiClient.generateFreshMixedQuestions(updatedSeen)
                val freshList = result.questions
                if (accountSession != com.spark.data.local.AccountSessionManager.generation) return@launch
                if (freshList.isNotEmpty() && freshList.size >= 4) {
                    suggestedQuestions = freshList
                    questionsAreAI = result.isAI
                    val finalSeen = updatedSeen + freshList.map { it.question }
                    seenQuestionsSet = finalSeen
                    SparkAISeenStorage.addSeen(context, freshList.map { it.question })
                    val message = if (result.isAI) "AI-generated questions refreshed" else "Suggested questions refreshed"
                    Toast.makeText(context, message, Toast.LENGTH_SHORT).show()
                } else {
                    suggestedQuestions = LocalSparkContent.getDiverseMultidisciplinaryMix(updatedSeen)
                    questionsAreAI = false
                }
            } catch (e: Exception) {
                suggestedQuestions = LocalSparkContent.getDiverseMultidisciplinaryMix(updatedSeen)
                questionsAreAI = false
            } finally {
                isRefreshingQuestions = false
            }
        }
    }

    // Generate story-driven quest from tapped question
    fun selectAndGenerateQuest(questionItem: QuestionCardItem) {
        val selectedQuestionIsAI = questionsAreAI
        selectedQuestionText = questionItem.question
        generationFailed = false
        isGeneratingQuest = true
        activeQuest = null
        questClaimed = false
        wormholeMessages = emptyList()
        wormholeQuestion = ""

        coroutineScope.launch {
            try {
                val result = aiClient.generateSparkQuest(
                    questionOrTopic = questionItem.question,
                    categoryPreference = questionItem.domain,
                    allowLocalFallback = !selectedQuestionIsAI,
                    purpose = "question"
                )
                if (accountSession != com.spark.data.local.AccountSessionManager.generation) return@launch
                activeQuest = result
            } catch (e: kotlinx.coroutines.CancellationException) {
                throw e
            } catch (e: Exception) {
                if (selectedQuestionIsAI) {
                    generationFailed = true
                } else {
                    activeQuest = LocalSparkContent.getCuratedHighQualityFallback(questionItem.question)
                }
            } finally {
                isGeneratingQuest = false
                coroutineScope.launch {
                    scrollState.scrollTo(0)
                }
            }
        }
    }

