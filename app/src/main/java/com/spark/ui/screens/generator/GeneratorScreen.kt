object SparkAISeenStorage {
    fun getSeen(context: android.content.Context): Set<String> {
        val prefs = com.spark.data.local.AccountSessionManager.preferences(context, "spark_ai_seen")
        return prefs.getStringSet("seen_questions", emptySet()) ?: emptySet()
    }

    fun addSeen(context: android.content.Context, newQuestions: Collection<String>) {
        val prefs = com.spark.data.local.AccountSessionManager.preferences(context, "spark_ai_seen")
        val current = (prefs.getStringSet("seen_questions", emptySet()) ?: emptySet()).toMutableSet()
        current.addAll(newQuestions)
        val trimmed = if (current.size > 200) current.toList().takeLast(200).toSet() else current
        prefs.edit().putStringSet("seen_questions", trimmed).apply()
    }
}

@Composable
fun SparkAIScreen(
    viewModel: DashboardViewModel = koinViewModel(),
    modifier: Modifier = Modifier
) {
