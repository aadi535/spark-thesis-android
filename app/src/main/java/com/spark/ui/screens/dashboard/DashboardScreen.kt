@Composable
fun ActionSparkButton(isReady: Boolean, isGenerating: Boolean, onClick: () -> Unit) {
    val buttonText = if (isGenerating) "Generating Spark..." else "Give Me Today's Spark!"

    val backgroundBrush = if (isReady && !isGenerating) {
        Brush.horizontalGradient(
            colors = listOf(SparkCyan, SparkCyan) // Cyan to Blue gradient
        )
    } else if (isGenerating) {
        androidx.compose.ui.graphics.SolidColor(SparkCyan.copy(alpha = 0.18f))
    } else {
        androidx.compose.ui.graphics.SolidColor(CardBackground.copy(alpha = 0.5f))
    }

    val textColor = if (isReady && !isGenerating) AppBackground else if (isGenerating) SparkCyan else TextSecondary

    SpringClickable(
        modifier = Modifier
            .fillMaxWidth()
            .height(64.dp)
            .clip(RoundedCornerShape(20.dp))
            .background(backgroundBrush)
            .border(1.dp, if (isReady) Color.Transparent else SurfaceVariant, RoundedCornerShape(20.dp)),
        onClick = { if (isReady && !isGenerating) onClick() }
    ) {
        Row(
            modifier = Modifier.fillMaxSize(),
            horizontalArrangement = Arrangement.Center,
            verticalAlignment = Alignment.CenterVertically
        ) {
            if (isGenerating) {
                CircularProgressIndicator(modifier = Modifier.size(24.dp), color = textColor, strokeWidth = 2.dp)
                Spacer(modifier = Modifier.width(12.dp))
            } else {
                Text("⚡", color = textColor, fontSize = 20.sp)
                Spacer(modifier = Modifier.width(8.dp))
            }
            Text(buttonText, color = textColor, fontSize = 18.sp, fontFamily = com.spark.ui.theme.SparkFont, fontWeight = FontWeight.SemiBold)
        }
    }
}

// ═══════════════════════════════════════════════════════════
// SPRING CLICKABLE UTILITY
// ═══════════════════════════════════════════════════════════
@Composable
fun SpringClickable(modifier: Modifier = Modifier, onClick: () -> Unit, content: @Composable () -> Unit) {
    var isPressed by remember { mutableStateOf(false) }
    val scale by animateFloatAsState(
        targetValue = if (isPressed) 0.96f else 1.0f,
        animationSpec = spring(dampingRatio = 0.6f, stiffness = 400f),
        label = "scale"
    )

    Box(
        modifier = modifier
            .scale(scale)
            .pointerInput(Unit) {
                awaitPointerEventScope {
                    while (true) {
                        awaitFirstDown()
                        isPressed = true
                        val up = waitForUpOrCancellation()
                        isPressed = false
                        if (up != null) onClick()
                    }
                }
            }
    ) { content() }
}
