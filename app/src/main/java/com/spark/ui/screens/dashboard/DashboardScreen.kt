@Composable
fun DashboardScreen(
    onLogout: () -> Unit,
    onNavigateToGenerator: () -> Unit,
    viewModel: DashboardViewModel = koinViewModel(),
    modifier: Modifier = Modifier
) {
    val context = androidx.compose.ui.platform.LocalContext.current
    val progressSync: com.spark.data.network.ProgressSync = org.koin.compose.koinInject()
    var selectedTime by remember { mutableStateOf<String?>(null) }
    var selectedMood by remember { mutableStateOf<String?>(null) }

    var selectedTopicTab by remember { mutableStateOf("Wonders") }
    var expandedSubjectId by remember { mutableStateOf<String?>(null) }
    var expandedLevelId by remember { mutableStateOf<String?>(null) }
    var finalSelectedTopic by remember { mutableStateOf<String?>(null) }

    var isGenerating by remember { mutableStateOf(false) }
    var isSparkGenerated by remember { mutableStateOf(false) }

    val isSparkExpanded by viewModel.isSparkExpanded.collectAsState()
    val currentSpark by viewModel.currentSpark.collectAsState()
    val chatMessages by viewModel.chatMessages.collectAsState()

    val state by viewModel.state.collectAsState()

    LaunchedEffect(state) {
        when (val s = state) {
            is DashboardState.Generating -> {
                isGenerating = true
            }
            is DashboardState.Generated -> {
                isGenerating = false
                isSparkGenerated = true
                val stepsText = s.spark.steps?.joinToString("\n- ", prefix = "- ") ?: "- Explore the topic"
                viewModel.currentSpark.value = GeneratedSpark(
                    title = s.spark.title ?: "Today's Discovery",
                    content = "${s.spark.hook ?: ""}\n\n${s.spark.description ?: ""}\n\nSteps:\n$stepsText\n\nFun Fact: ${s.spark.funFact ?: ""}",
                    type = s.spark.category ?: "Deep Dive",
                    isAI = s.spark.isAI,
                    emoji = s.spark.icon ?: "✨"
                )
                viewModel.isSparkExpanded.value = true
                viewModel.resetState() // Reset so it doesn't trigger again
            }
            is DashboardState.Error -> {
                isGenerating = false
                // Handle error if needed
                viewModel.resetState()
            }
            DashboardState.Idle -> {}
        }
    }

    val scrollState = rememberScrollState()
    val coroutineScope = rememberCoroutineScope()

    Box(
        modifier = modifier
            .fillMaxSize()
            .appBackdrop()
    ) {
        Column(
            modifier = Modifier
                .fillMaxSize()
                .statusBarsPadding() // Pushes content below the top network/battery bar
                .verticalScroll(scrollState)
                .padding(horizontal = 24.dp)
                .padding(top = 8.dp, bottom = 100.dp)
        ) {
            // ─── Header ───
            HeaderSection(xp = com.spark.ui.screens.main.GlobalUserState.xp.toLong())

            Spacer(modifier = Modifier.height(12.dp))

            // ─── Time Pills ───
            TimeSelectionSection(selectedTime) { selectedTime = it }

            Spacer(modifier = Modifier.height(12.dp))

            // ─── Mood Pills ───
            MoodSelectionSection(selectedMood) { selectedMood = it }

            Spacer(modifier = Modifier.height(12.dp))

            // ─── Topic Preference ───
            TopicPreferenceSection(
                selectedTab = selectedTopicTab,
                onTabSelected = {
                    selectedTopicTab = it
                    expandedSubjectId = null
                    expandedLevelId = null
                },
                expandedSubjectId = expandedSubjectId,
                onSubjectExpand = { expandedSubjectId = if (expandedSubjectId == it) null else it },
                expandedLevelId = expandedLevelId,
                onLevelExpand = { expandedLevelId = if (expandedLevelId == it) null else it },
                selectedTopic = finalSelectedTopic,
                onTopicSelect = { finalSelectedTopic = it }
            )

            // ─── Inline Generated Spark ───
            AnimatedVisibility(
                visible = !isSparkExpanded && currentSpark != null,
                enter = expandVertically() + fadeIn(),
                exit = shrinkVertically() + fadeOut()
            ) {
                Column {
                    Spacer(modifier = Modifier.height(24.dp))
                    currentSpark?.let { spark ->
                        GeneratedSparkInlineCard(
                            spark = spark,
                            onMaximize = { viewModel.isSparkExpanded.value = true }
                        )
                    }
                }
            }
        }

        // Generate button at bottom
        if (!isSparkExpanded) {
            val isReady = selectedTime != null && selectedMood != null
            Box(
                modifier = Modifier
                    .align(Alignment.BottomCenter)
                    .fillMaxWidth()
                    .background(AppBackground.copy(alpha = 0.85f))
                    .padding(16.dp)
            ) {
                ActionSparkButton(isReady = isReady, isGenerating = isGenerating) {
                    if (!isGenerating && isReady) {
                        viewModel.generateSpark(
                            mood = selectedMood ?: "Curious",
                            time = selectedTime ?: "10m",
                            topic = finalSelectedTopic ?: selectedTopicTab
                        )
                    }
                }
            }
        }

        // ─── Full Screen Expanded Spark ───
        AnimatedVisibility(
            visible = isSparkExpanded && currentSpark != null,
            enter = slideInVertically(initialOffsetY = { it }) + fadeIn(),
            exit = slideOutVertically(targetOffsetY = { it }) + fadeOut(),
            modifier = Modifier.fillMaxSize().zIndex(10f)
        ) {
            currentSpark?.let { spark ->
                GeneratedSparkFullScreen(
                    spark = spark,
                    chatMessages = chatMessages,
                    onSendMessage = { text ->
                        viewModel.chatMessages.value = viewModel.chatMessages.value + ChatMessage(id = java.util.UUID.randomUUID().toString(), text = text, isUser = true)
                        coroutineScope.launch {
                            val answer = viewModel.sendWormholeMessage(
                                question = text,
                                sparkTitle = spark.title ?: "",
                                sparkDescription = spark.content
                            )
                            viewModel.chatMessages.value = viewModel.chatMessages.value + ChatMessage(
                                id = java.util.UUID.randomUUID().toString(),
                                text = answer,
                                isUser = false
                            )
                        }
                    },
                    onMinimize = { viewModel.isSparkExpanded.value = false },
                    onComplete = {
                        // 1. Update Global State
                        val sparkXp = 150
                        com.spark.ui.screens.main.GlobalUserState.completeTask(sparkXp)
                        com.spark.ui.screens.main.GlobalUserState.saveProgress(context)

                        // 2. Add node to Mind Palace
                        com.spark.ui.screens.main.MindPalaceData.addSparkToMindPalace(
                            title = spark.title,
                            category = spark.type,
                            hook = spark.content.split("\n").firstOrNull() ?: "",
                            xp = sparkXp,
                            fullContent = spark.content,
                            emoji = spark.emoji,
                            context = context
                        )

                        progressSync.saveCompletion(com.spark.ui.screens.main.GlobalUserState.xp,
                            com.spark.ui.screens.main.MindPalaceData.completedHistory())

                        // 4. Clear ViewModel state
                        isSparkGenerated = false
                        viewModel.closeSpark()
                    }
                )
            }
        }
    }
}

