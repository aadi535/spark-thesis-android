@Composable
fun TopicChip(title: String, selectedTopic: String?, isOutlined: Boolean = false, onClick: () -> Unit) {
    val isSelected = title == selectedTopic
    val modifier = if (isOutlined) {
        Modifier.border(1.dp, WondersGreen, RoundedCornerShape(100.dp))
    } else {
        Modifier.border(1.dp, if (isSelected) TextSecondary else SurfaceVariant, RoundedCornerShape(100.dp))
    }

    Box(
        modifier = Modifier
            .clip(RoundedCornerShape(100.dp))
            .background(if (isSelected) TextSecondary.copy(alpha = 0.2f) else AppBackground)
            .then(modifier)
            .clickable(onClick = onClick)
            .padding(horizontal = 16.dp, vertical = 10.dp)
    ) {
        Text(title, color = if (isSelected || isOutlined) TextPrimary else TextSecondary, fontSize = 14.sp, fontFamily = com.spark.ui.theme.SparkFont, fontWeight = FontWeight.Medium)
    }
}

