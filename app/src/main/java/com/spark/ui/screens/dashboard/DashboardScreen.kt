    Column {
        Row(verticalAlignment = Alignment.CenterVertically) {
            FeatureGlyph("⭐", size = 18.dp)
            Spacer(modifier = Modifier.width(8.dp))
            Text("Topic preference ", color = TextPrimary, fontSize = 18.sp, fontFamily = com.spark.ui.theme.SparkFont, fontWeight = FontWeight.SemiBold)
            Text("(optional)", color = TextPrimary, fontFamily = com.spark.ui.theme.SparkFont, fontSize = 16.sp)
        }
        Spacer(modifier = Modifier.height(16.dp))

        Row(horizontalArrangement = Arrangement.spacedBy(12.dp)) {
            TopicTab("🌟", "Classics", isSelected = selectedTab == "Classics") { onTabSelected("Classics") }
            TopicTab("⚛️", "Mastery", isSelected = selectedTab == "Mastery") { onTabSelected("Mastery") }
            TopicTab("✨", "Wonders", isSelected = selectedTab == "Wonders") { onTabSelected("Wonders") }
        }

        Spacer(modifier = Modifier.height(12.dp))

        Box(
            modifier = Modifier
                .fillMaxWidth()
                .clip(RoundedCornerShape(20.dp))
                .background(CardBackground.copy(alpha = 0.5f))
                .border(1.dp, SurfaceVariant.copy(alpha = 0.3f), RoundedCornerShape(20.dp))
                .padding(16.dp)
        ) {
            Column {
                if (selectedTab == "Classics") {
                    Text("ORIGINAL FAVORITES", color = TextPrimary, fontSize = 12.sp, fontFamily = com.spark.ui.theme.SparkFont, fontWeight = FontWeight.SemiBold, letterSpacing = 1.sp)
                    Spacer(modifier = Modifier.height(16.dp))
                    OptWrapLayout {
                        DashboardConstants.INTERESTS.forEach { interest ->
                            TopicChip(interest, selectedTopic, isOutlined = interest == "Surprise me!") { onTopicSelect(interest) }
                        }
                    }
                } else if (selectedTab == "Mastery") {
                    Text("ACADEMIC MASTERY — TAP A SUBJECT TO EXPAND", color = TextPrimary, fontSize = 12.sp, fontFamily = com.spark.ui.theme.SparkFont, fontWeight = FontWeight.SemiBold, letterSpacing = 1.sp)
                    Spacer(modifier = Modifier.height(16.dp))

                    DashboardConstants.MASTERY_SUBJECTS.forEach { subject ->
                        ExpandableCategoryRow(
                            label = subject.label, color = subject.color,
                            isExpanded = expandedSubjectId == subject.id,
                            onClick = { onSubjectExpand(subject.id) }
                        ) {
                            Column(modifier = Modifier.fillMaxWidth().padding(top = 16.dp)) {
                                Text("CHOOSE YOUR LEVEL", color = TextPrimary, fontSize = 12.sp, fontFamily = com.spark.ui.theme.SparkFont, fontWeight = FontWeight.SemiBold, letterSpacing = 1.sp)
                                Spacer(modifier = Modifier.height(12.dp))
                                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                                    subject.levels.forEach { level ->
                                        LevelChip(level, expandedLevelId == level, subject.color) { onLevelExpand(level) }
                                    }
                                }

                                if (expandedLevelId != null && subject.levels.contains(expandedLevelId)) {
                                    Spacer(modifier = Modifier.height(24.dp))
                                    Text("${expandedLevelId!!.uppercase()} TOPICS", color = TextPrimary, fontSize = 12.sp, fontFamily = com.spark.ui.theme.SparkFont, fontWeight = FontWeight.SemiBold, letterSpacing = 1.sp)
                                    Spacer(modifier = Modifier.height(12.dp))

                                    Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
                                        subject.subtopicsByLevel[expandedLevelId]?.forEach { subtopic ->
                                            SubtopicCard(subtopic, isSelected = selectedTopic == subtopic.id) {
                                                onTopicSelect(subtopic.id)
                                            }
                                        }
                                    }
                                }
                            }
                        }
                        Spacer(modifier = Modifier.height(12.dp))
                    }
                } else if (selectedTab == "Wonders") {
                    Text("VAULT OF WONDERS — TAP TO EXPAND", color = TextPrimary, fontSize = 12.sp, fontFamily = com.spark.ui.theme.SparkFont, fontWeight = FontWeight.SemiBold, letterSpacing = 1.sp)
                    Spacer(modifier = Modifier.height(16.dp))

                    DashboardConstants.WONDER_SUBJECTS.forEach { wonder ->
                        ExpandableCategoryRow(
                            label = wonder.label, color = wonder.color,
                            isExpanded = expandedSubjectId == wonder.id,
                            onClick = { onSubjectExpand(wonder.id) }
                        ) {
                            OptWrapLayout(modifier = Modifier.fillMaxWidth().padding(top = 16.dp)) {
                                wonder.options.forEach { option ->
                                    TopicChip(option, selectedTopic) { onTopicSelect(option) }
                                }
                            }
                        }
                        Spacer(modifier = Modifier.height(12.dp))
                    }
                }
            }
        }

        if (!selectedTopic.isNullOrEmpty()) {
            Spacer(modifier = Modifier.height(16.dp))
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .clip(RoundedCornerShape(12.dp))
                    .background(CardBackground) // Dark green
                    .border(1.dp, WondersGreen.copy(alpha = 0.5f), RoundedCornerShape(12.dp))
                    .padding(16.dp),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Box(modifier = Modifier.size(16.dp).background(WondersGreen, RoundedCornerShape(4.dp)), contentAlignment = Alignment.Center) {
                        Icon(Icons.Default.Close, contentDescription = "Check", tint = AppBackground, modifier = Modifier.size(12.dp))
                    }
                    Spacer(modifier = Modifier.width(8.dp))
                    Text(selectedTopic, color = WondersGreen, fontWeight = FontWeight.SemiBold)
                }
                Box(
                    modifier = Modifier
                        .clip(RoundedCornerShape(100.dp))
                        .background(Color.White.copy(alpha = 0.1f))
                        .softPress { onTopicSelect("") }
                        .padding(horizontal = 12.dp, vertical = 6.dp)
                ) {
                    Text("Clear", color = TextPrimary, fontSize = 12.sp, fontWeight = FontWeight.SemiBold)
                }
            }
        }
    }
}

// A simple flex wrap layout for Chips
@Composable
fun OptWrapLayout(modifier: Modifier = Modifier, content: @Composable () -> Unit) {
    @OptIn(ExperimentalLayoutApi::class)
    FlowRow(
        modifier = modifier,
        horizontalArrangement = Arrangement.spacedBy(8.dp),
        verticalArrangement = Arrangement.spacedBy(8.dp)
    ) {
        content()
    }
}

@Composable
fun ExpandableCategoryRow(
    label: String, color: Color, isExpanded: Boolean, onClick: () -> Unit,
    content: @Composable () -> Unit
) {
    Column(modifier = Modifier.fillMaxWidth()) {
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .clickable(onClick = onClick)
                .padding(vertical = 12.dp),
            horizontalArrangement = Arrangement.SpaceBetween,
            verticalAlignment = Alignment.CenterVertically
        ) {
            Text(label, color = if (isExpanded) color else TextPrimary, fontFamily = com.spark.ui.theme.SparkFont, fontWeight = FontWeight.SemiBold, fontSize = 18.sp)
            Icon(
                if (isExpanded) Icons.Default.KeyboardArrowUp else Icons.Default.KeyboardArrowDown,
                contentDescription = null,
                tint = if (isExpanded) color else TextSecondary
            )
        }

        AnimatedVisibility(visible = isExpanded, enter = expandVertically(), exit = shrinkVertically()) {
            content()
        }
    }
}

